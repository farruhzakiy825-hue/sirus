#!/usr/bin/env python3
"""Build the Strategy Tester copy of Sirus Brain V8 (package 47).

The live EA has ~2800 inputs; the Strategy Tester refuses that many ("too many inputs"). This script
writes Sirus_Brain_V8_Tester.mq5 + SirusT/*.mqh, a copy in which every input outside the owner's main
groups becomes a constant with the same default. The live files are not touched - run this again after
every change:   python3 tools/make_tester_build.py
Kept as inputs: the "SIRUS ▸ 1..7" groups, YADRO and the probability table.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, DST = os.path.join(ROOT, 'Sirus'), os.path.join(ROOT, 'SirusT')
KEEP_GROUP = re.compile(r'^input group "(SIRUS ▸ |YADRO ▸ |EHTIMOL JADVALI ▸ )')
GROUP = re.compile(r'^input group ')
INPUT = re.compile(r'^input\s+')

os.makedirs(DST, exist_ok=True)
kept = const = 0
for name in sorted(os.listdir(SRC)):
    if not name.endswith('.mqh'):
        continue
    text = open(os.path.join(SRC, name), encoding='utf-8-sig').read()
    out, keep = [], False
    for line in text.split('\n'):
        if GROUP.match(line):
            keep = bool(KEEP_GROUP.match(line))
            out.append(line if keep else '// [tester build] ' + line)
        elif INPUT.match(line):
            if keep:
                kept += 1
                out.append(line)
            else:
                const += 1
                out.append(INPUT.sub('const ', line, count=1))
        else:
            out.append(line)
    open(os.path.join(DST, name), 'w', encoding='utf-8-sig', newline='\n').write('\n'.join(out))

main = open(os.path.join(ROOT, 'Sirus_Brain_V8.mq5'), encoding='utf-8-sig').read()
main = main.replace('#include "Sirus/', '#include "SirusT/')
header = ('// STRATEGY TESTER BUILD - generated by tools/make_tester_build.py from Sirus_Brain_V8.mq5.\n'
          '// Do not edit: change the live files and run the script again. Only the main groups are inputs here;\n'
          '// every other setting is a constant with the live default (the tester refuses ~2800 inputs).\n')
open(os.path.join(ROOT, 'Sirus_Brain_V8_Tester.mq5'), 'w', encoding='utf-8-sig', newline='\n').write(header + main)
print(f'tester build: {kept} inputs kept, {const} turned into constants')
